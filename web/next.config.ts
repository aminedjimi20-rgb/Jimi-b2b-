import type { NextConfig } from "next";
import createNextIntlPlugin from "next-intl/plugin";

const withNextIntl = createNextIntlPlugin("./i18n/request.ts");

const nextConfig: NextConfig = {
  images: {
    formats: ["image/avif", "image/webp"],
  },
  // En-têtes de sécurité HTTP de base — pas de Content-Security-Policy ici :
  // le site utilise des scripts inline (JSON-LD, hydratation Next) et une
  // CSP mal calibrée casserait le rendu ; à mettre en place séparément avec
  // des tests dédiés (nonce/hash par script) plutôt qu'ajoutée à l'aveugle.
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "SAMEORIGIN" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=()",
          },
        ],
      },
    ];
  },
};

export default withNextIntl(nextConfig);
